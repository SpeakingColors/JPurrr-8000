#!/usr/bin/env python3
"""Generates core/src/melody_gen_data.h from data/melody_gen.json (what the melody generator learned from the 22 uplifting
trance melodies: bar rhythms and chord loops only). tools/melody_gen.src.js carries the same data for the mockup."""
import json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = json.load(open(os.path.join(root, 'data/melody_gen.json')))
out = ['// GENERATED by tools/gen_melody_gen_cpp.py from data/melody_gen.json. Do not edit.',
       '#pragma once', 'namespace jpurrr { namespace gendata {',
       'struct Step { signed char s, n; };                    // onset step and length in 16ths',
       'struct Rhythm { int w; const Step* st; int n; };      // w: how often this rhythm appears in the 22 melodies',
       'struct ChordStep { signed char off; bool minor; };    // semitone offset from the key note']
FAM = d['families']
k = 0
rhy = []
for f in FAM:
    rows = []
    for r in d['rhythms'][f]:
        name = 'st%d' % k; k += 1
        out.append('inline constexpr Step %s[] = {%s};' % (name, ','.join('{%d,%d}' % (s, n) for s, n in r['r'])))
        rows.append('{%d,%s,%d}' % (r['w'], name, len(r['r'])))
    out.append('inline constexpr Rhythm rh_%s[] = {%s};' % (f, ','.join(rows)))
    rhy.append((f, len(rows)))
out.append('inline constexpr Rhythm const* kRhythms[5] = {%s};' % ','.join('rh_' + f for f, _ in rhy))
out.append('inline constexpr int kRhythmCount[5] = {%s};' % ','.join(str(n) for _, n in rhy))
ends = []
for i, e in enumerate(d['endings']):
    out.append('inline constexpr Step end%d[] = {%s};' % (i, ','.join('{%d,%d}' % (s, n) for s, n in e)))
    ends.append('{0,end%d,%d}' % (i, len(e)))
out.append('inline constexpr Rhythm kEndings[] = {%s};' % ','.join(ends))
out.append('inline constexpr int kNumEndings = %d;' % len(d['endings']))
for mode in ('minor', 'major'):
    rows = []
    for i, p in enumerate(d['progressions'][mode]):
        name = 'pg_%s%d' % (mode[:3], i)
        out.append('inline constexpr ChordStep %s[] = {%s};' % (name, ','.join('{%d,%s}' % (o, 'true' if q == 'm' else 'false') for o, q in p)))
        rows.append('{%s,%d}' % (name, len(p)))
    out.append('struct Prog { const ChordStep* c; int n; };' if mode == 'minor' else '')
    out.append('inline constexpr Prog kProg_%s[] = {%s};' % (mode, ','.join(rows)))
    out.append('inline constexpr int kNumProg_%s = %d;' % (mode, len(d['progressions'][mode])))
out.append('} }')
open(os.path.join(root, 'core/src/melody_gen_data.h'), 'w').write('\n'.join(x for x in out if x != '') + '\n')
print('wrote core/src/melody_gen_data.h:', sum(len(d['rhythms'][f]) for f in FAM), 'rhythms,', len(d['endings']), 'endings,',
      len(d['progressions']['minor']), '+', len(d['progressions']['major']), 'progressions')
