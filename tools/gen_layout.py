#!/usr/bin/env python3
"""Generates plugin/Source/Editor/layout_gen.cpp from data/layout.json (dumped from the mockup by tools/dump_layout.js)."""
import json, re, sys, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = json.load(open(os.path.join(root, 'data/layout.json')))
out = []
w = out.append

def cs(s):
    b = s.encode('utf-8'); r = ''
    for c in b:
        if c == 0x22: r += '\\"'
        elif c == 0x5c: r += '\\\\'
        elif 32 <= c < 127: r += chr(c)
        else: r += '\\%03o' % c
    return '"' + r + '"'
def f(x): return ('%.2f' % x).rstrip('0') + 'f' if x != int(x) else '%d.f' % int(x)
def R(r): return '{%s,%s,%s,%s}' % (f(r['x']), f(r['y']), f(r['w']), f(r['h']))
FAM = {'Barlow': 'kBody', 'Barlow Condensed': 'kCond', 'JetBrains Mono': 'kMono'}
def F(o): return '{%s,%s,%d,%s,%s}' % (FAM[o['fam']], f(o['size']), o['weight'], f(o['ls']), 'true' if o.get('italic') else 'false')
TOKS = ['pnl','pnl2','pnl3','edge','sbd','hi','ttl','lbl','lbl2','knob','knobhi','ind','cap','led','ledoff','acc','acc2','lcdbg','lcdfg','lcdoff','hdr','hdrfg','sel','selfg','dsp','dspline','dspfill','dspgrid','dspaccent','logo','btnbg','btnbd','wordmark']
def col(c):
    m = re.match(r'rgba?\(([^)]*)\)', c); p = [float(x) for x in m.group(1).replace('/', ',').split(',')]
    a = p[3] if len(p) > 3 else 1.0
    return '0x%02x%02x%02x%02x' % (round(a * 255), int(p[0]), int(p[1]), int(p[2]))

w('// GENERATED by tools/gen_layout.py from data/layout.json (tools/dump_layout.js). Do not edit.')
w('#include "Layout.h"')
w('namespace jp::layout {')
w('namespace {')

hb_ids = set(i['id'] for p in [d['chrome']] + list(d['pages'].values()) for i in p if i['k'] == 'hbtn')
drop_text_ids = {'msg'}

lines_all = []; opts_all = []
def make_arr(name):
    def arr(typ, var, rows):
        if not rows: return 'Span<%s>{nullptr,0}' % typ
        w('const %s %s_%s[] = {' % (typ, name, var)); w(',\n'.join('  ' + r for r in rows)); w('};')
        return 'Span<%s>{%s_%s,%d}' % (typ, name, var, len(rows))
    return arr
def emit_texts(name, arr, items, skip_rects=()):
    texts = []; allines = []
    for i in items:
        if i['k'] != 'text' or i.get('id') in drop_text_ids or i['rect'] in skip_rects: continue
        start = len(allines)
        for l in i['lines']: allines.append('{%s,%s,%s,%s}' % (cs(l['t']), f(l['x']), f(l['w']), f(l['base'])))
        tok = TOKS.index(i['tok']) if i.get('tok') in TOKS else -1
        texts.append((i, start, len(i['lines']), tok))
    arr('Line', 'lines', allines)
    # texts reference lines through absolute pointers built after the Line array exists
    trows = []
    for i, st, n, tok in texts:
        trows.append('{%s,%s,\'%s\',%d,%s,%s,{%s_lines+%d,%d}}' % (cs(i.get('id') or ''), F(i['f']), i['al'], tok, col(i['col']) if 'col' in i else '0xffffffff', R(i['rect']), name, st, n))
    return arr('Text', 'texts', trows), texts
def emit_page(name, items, h, hk=None, stripy=None):
    arr = make_arr(name)
    vrects = [i['rect'] for i in items if i['k'] == 'vtext']   # vertical labels are drawn as vtext; the dump also holds their glyph-per-line text
    P = {}
    P['texts'], _ = emit_texts(name, arr, items, vrects)
    P['secs'] = arr('Sec', 'secs', ['{%s,%s,%s,%s}' % (R(i['rect']), cs(i['title']), R(i['ttl']), R(i['span'])) for i in items if i['k'] == 'sec'])
    P['knobs'] = arr('Knob', 'knobs', ['{%s,%s}' % (cs(i['id']), R(i['rect'])) for i in items if i['k'] == 'knob'])
    P['sliders'] = arr('Slider', 'sliders', ['{%s,%s,%d,%s}' % (cs(i['id']), R(i['rect']), i['hh'], f(i['tk'])) for i in items if i['k'] == 'slider'])
    P['switches'] = arr('Switch', 'switches', ['{%s,%s,%s}' % (cs(i['id']), R(i['rect']), 'true' if i['mom'] else 'false') for i in items if i['k'] == 'switch'])
    oa = []; orow = []
    for i in items:
        if i['k'] != 'opts': continue
        st = len(oa)
        for o in i['opts']: oa.append('{%d,%s,%s}' % (o['v'], R(o['r']), R(o['led'])))
        orow.append((i, st, len(i['opts'])))
    arr('Opt', 'optv', oa)
    P['opts'] = arr('Opts', 'opts', ['{%s,%s,{%s_optv+%d,%d}}' % (cs(i['id']), R(i['rect']), name, st, n) for i, st, n in orow])
    P['selects'] = arr('Select', 'selects', ['{%s,%s,%s,%s,%d}' % (cs(i['id']), cs(i['mp']), R(i['rect']), F(i['f']), i['n']) for i in items if i['k'] == 'select'])
    P['canvases'] = arr('Canvas', 'canvases', ['{%s,%s,%d,%d}' % (cs(i['id']), R(i['rect']), i['cw'], i['ch']) for i in items if i['k'] == 'canvas'])
    P['tips'] = arr('Tip', 'tips', ['{%s,%s,%s}' % (R(i['rect']), cs(i['tip']), cs(i.get('for', ''))) for i in items if (i['k'] in ('tip', 'hbtn', 'pname')) and i.get('tip')])
    P['hbtns'] = arr('HBtn', 'hbtns', ['{%s,%s,%s,%s,%s}' % (cs(i['id']), R(i['rect']), cs(i['t']), 'true' if i.get('tab') else 'false', 'true' if i.get('sq') else 'false') for i in items if i['k'] == 'hbtn'])
    P['mbps'] = arr('Rect', 'mbps', [R(i['rect']) for i in items if i['k'] == 'mbp'])
    P['vtexts'] = arr('VText', 'vtexts', ['{%s,%s,%s}' % (cs(i['t']), R(i['rect']), F(i['f'])) for i in items if i['k'] == 'vtext'])
    P['cats'] = arr('Cat', 'cats', ['{%s}' % R(i['rect']) for i in items if i['k'] == 'cat'])
    P['bbtns'] = arr('BlockBtn', 'bbtns', ['{%s,%s,{%s,%s,%s,false,%s},%s,%s}' % (cs(i['mp']), 'true' if i['more'] else 'false', cs(i['id']), R(i['rect']), cs(i['t']), 'true' if i['more'] else 'false', F(i['f']), cs(i['tip'])) for i in items if i['k'] == 'bbtn'])
    lcd = [i for i in items if i['k'] == 'lcd']
    lc = '{%s,%s,%s,%s}' % (R(lcd[0]['rect']), R(lcd[0]['l1']), R(lcd[0]['l2']), F(lcd[0]['f'])) if lcd else '{}'
    w('const Page %s_page = {%d,%d,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s};' % (name, hk if hk is not None else h, h, f(stripy or 0), P['secs'], P['texts'], P['knobs'], P['sliders'], P['switches'], P['opts'], P['selects'], P['canvases'], P['tips'], P['hbtns'], P['mbps'], P['vtexts'], P['cats'], P['bbtns'], 'true' if lcd else 'false', lc))

for nm in ['sound', 'chain', 'master']:
    emit_page(nm, d['pages'][nm], d['pageH'][nm], d['pageHk'][nm], d['stripY'][nm])
emit_page('chrome', d['chrome'], 0)

# keyboard strip (y relative to the strip top; add Page::stripY)
S = d['strip']
sarr = make_arr('strip')
is_kl = lambda t: t['col'] == 'rgb(107, 114, 128)' and t['lines'][0]['t'][0] == 'C'
# the KEYS / VEL readout (#kinfo, v3.7) over the keys is drawn live by the plugin
is_info = lambda t: t['rect']['x'] >= S['keysRect']['x'] and not is_kl(t)
stexts, _ = emit_texts('strip', sarr, [t for t in S['texts'] if not is_kl(t) and not is_info(t)])
sknobs = sarr('StripKnob', 'knobs', ['{%s,%s,%s,%s}' % (cs(k['id']), R(k['rect']), R(k['tipRect']), cs(k['tip'])) for k in S['knobs']])
wrows = []
for wh in S['wheels']:
    wrows.append('{%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s}' % (cs(wh['id']), 'true' if wh['pitch'] else 'false', R(wh['rect']), R(wh['handle']), R(wh['line']) if wh['line'] else '{0.f,0.f,0.f,0.f}', R(wh['name']), R(wh['scale']), f(wh['wn']), f(wh['rect']['h'] - 2 - 16), cs(wh['aria']), cs(wh['tip'])))
swheels = sarr('Wheel', 'wheels', wrows)
skeys = sarr('Key', 'keys', ['{%d,%s,%s}' % (k['n'], 'true' if k['black'] else 'false', R(k['rect'])) for k in sorted(S['keys'], key=lambda k: (k['black'], k['n']))])
# C labels: text line of the .kl span, matched to its white key by note
klines = {}
for t in S['texts']:
    if t['id'] == '' and t['f']['size'] == 16.7 and t['col'] == 'rgb(107, 114, 128)':
        l = t['lines'][0]; klines[t['lines'][0]['t']] = (t, l)
lrows = []
for lb in S['labels']:
    t, l = klines[lb['t']]
    lrows.append('{%d,%s,%s,%s,%s}' % (lb['n'], cs(lb['t']), f(l['x']), f(l['w']), f(l['base'])))
slabels = sarr('KeyLabel', 'labels', lrows)
kfont = [t for t in S['texts'] if t['col'] == 'rgb(107, 114, 128)'][0]
w('}')
w('const KeyStrip kStrip = {%s,%s,%s,%d,%d,%s,%s,%s,%s,%s,%s,%s};' % (R(S['rect']), R(S['keysRect']), R(S['whls']), min(k['n'] for k in S['keys']), max(k['n'] for k in S['keys']), F(kfont['f']), col(kfont['col']), swheels, skeys, slabels, stexts, sknobs))
# v3.8 PLAYER bar
PL = d['player']
PI = {i['id']: i for i in PL['items']}
def PLL(l): return '{%s,%s,%s}' % (f(l['x']), f(l['w']), f(l['base']))
def FN(o): return F(o)
pm = PL['menu']
plmenu = '{%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s}' % (f(pm['w']), f(pm['border']), f(pm['radius']), f(pm['gh']), f(pm['gpad']), f(pm['rh']), f(pm['rpadL']), f(pm['rpadR']), f(pm['rgap']),
    F(pm['gf']), F(pm['gsf']), F(pm['rf']), F(pm['rsf']), f(pm['above']), f(pm['minTop']), f(pm['maxH']), f(pm['minH']), f(pm['left']))
ptips = [(k, PI[k]) for k in ['play', 'prev', 'sel', 'next', 'bpmG', 'lockG', 'trG', 'load', 'exp', 'posG']]
w('namespace {')
w('const Tip player_tips[] = {%s};' % ','.join('{%s,%s,""}' % (R(v['rect']), cs(v['tip'])) for k, v in ptips))
w('}')
pbar = PL['rect']
fields = [
    f(PL['h']), f(PL['extra']), R(pbar), f(PL['radius']),
    F(PI['title']['f']), F(PI['play']['lbl']['f']), F(PI['bpmL']['f']), F(PI['sel']['name']['f']), F(PI['sel']['grp']['f']), F(PI['bpm']['f']), F(PI['posT']['small']['f']), F(PI['posT']['val']['f']),
    PLL(PI['title']['line']),
    R(PI['play']['rect']), R(PI['play']['icon']), R(PL['playOn']['icon']), PLL(PI['play']['lbl']['line']), PLL({'x': PL['playOn']['x'], 'w': PL['playOn']['w'], 'base': PI['play']['lbl']['line']['base']}),
    R(PI['prev']['rect']), R(PI['prev']['icon']), R(PI['next']['rect']), R(PI['next']['icon']),
    R(PI['sel']['rect']), R(PI['sel']['name']['rect']), f(PI['sel']['name']['base']), R(PI['sel']['grp']['rect']), f(PI['sel']['grp']['base']), R(PI['sel']['chev']), f(PI['sel']['pad']),
    R(PI['bpmG']['rect']), R(PI['bpm']['rect']), f(PI['bpm']['base']), PLL(PI['bpmL']['line']),
    R(PI['lockG']['rect']), R(PI['lock']['rect']), R(PI['lock']['led']), PLL(PI['lockL']['line']),
    R(PI['trG']['rect']), R(PI['tr']['rect']), f(PI['tr']['base']), PLL(PI['trL']['line']),
    R(PI['load']['rect']), R(PI['exp']['rect']), PLL(PI['load']['line']), PLL(PI['exp']['line']),
    R(PI['posG']['rect']), R(PI['pos']['rect']), R(PI['posT']['rect']), PLL(PI['posT']['small']['line']), PLL({'x': PI['posT']['val']['x'], 'w': PI['posT']['val']['w'], 'base': PI['posT']['val']['base']}), str(PI['pos']['cw']), str(PI['pos']['ch']),
    '{%s}' % ','.join(R(PI['sep%d' % k]['rect']) for k in range(4)), plmenu, 'Span<Tip>{player_tips,%d}' % len(ptips)]
w('const PlayerGeo kPlayer = {%s};' % ','.join(fields))
# v3.5 PARTS band
PT = d['parts']
def PB(o): return '{%s,%s}' % (R(o), f(o['base'] if o.get('base') is not None else 0))
def PC(c): return '{%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s}' % (R(c['rect']), PB(c['led']), PB(c['title']), PB(c['role']), PB(c['ed'] or {'x': 0, 'y': 0, 'w': 0, 'h': 0}), PB(c['prev']), PB(c['name']), PB(c['next']), PB(c['browse']), PB(c['chipsRow']), PB(c['chip']), PB(c['chipId']))
# the PANEL EDITS tag only exists on the edited card: take its box from the UPPER card for both
PT['cards']['l']['ed'] = PT['cards']['u']['ed']
PT['cards']['l']['ed'] = dict(PT['cards']['l']['ed'], x=PT['cards']['l']['ed']['x'])
M = PT['map']
w('namespace {')
w('const Line parts_btnlines[] = {%s};' % ','.join('{%s,%s,%s,%s}' % (cs(b['t']), f(b['line']['x']), f(b['line']['w']), f(b['line']['base'])) for b in PT['btns']))
w('const Text parts_btntexts[] = {%s};' % ','.join("{%s,%s,'c',-1,0xffffffff,%s,{parts_btnlines+%d,1}}" % (cs(b['id']), F({'fam': 'Barlow Condensed', 'size': b['f']['size'], 'weight': b['f']['weight'], 'ls': b['f']['ls']}), R(b['rect']), i) for i, b in enumerate(PT['btns'])))
w('const HBtn parts_btns[] = {%s};' % ','.join('{%s,%s,%s,false,%s}' % (cs(b['id']), R(b['rect']), cs(b['t']), 'true' if b['sq'] else 'false') for b in PT['btns']))
w('}')
w('const PartsGeo kParts = {%s,%s,%s,{%s,%s,%s,%s},%s,%s,{%s,%s,%s,%s,%s,%s,%s,%s},{parts_btns,%d},{parts_btntexts,%d}};' % (
    f(PT['top']), f(PT['hOpen'] - d['pageHk']['sound']), f(PT['stripYOpen']), R(PT['sec']['rect']), cs(PT['sec']['title']), R(PT['sec']['ttl']), R(PT['sec']['span']),
    PC(PT['cards']['l']), PC(PT['cards']['u']), R(M['rect']), PB(M['title']), PB(M['pill']), PB(M['text']), PB(M['sp']), PB(M['mini']), PB(M['oct']), PB(M['octI']), len(PT['btns']), len(PT['btns'])))
w('namespace {')
w('}')
w('const Page kPages[kNumPages] = {sound_page, chain_page, master_page};')
w('const Page kChrome = chrome_page;')
w('const int kChromeH = %d;' % d['design']['chromeH'])
ch = d['chrome']
def first(k): return [i for i in ch if i['k'] == k]
cheeks = first('cheek')
w('const Rect kHdr = %s, kFtr = %s, kCheekL = %s, kCheekR = %s, kPname = %s, kPinfo = %s, kMsg = %s;' % tuple(R(x['rect']) for x in [first('hdr')[0], first('ftr')[0], [c for c in cheeks if c['side']=='l'][0], [c for c in cheeks if c['side']=='r'][0], first('pname')[0], first('pinfo')[0], first('msg')[0]]))

# looks
