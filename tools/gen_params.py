#!/usr/bin/env python3
"""Generates core/include/jpurrr/params_gen.h and core/src/params_gen.cpp from data/params.json.
data/params.json is dumped from the mockup (window.__JP) with tools/dump_mockup.js."""
import json, os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = json.load(open(os.path.join(root, 'data', 'params.json')))
P = d['params']
def esc(s): return (s or '').replace('\\', '\\\\').replace('"', '\\"').replace('\n', ' ')
opts = []; start = {}
for p in P:
    if p['opts']:
        start[p['id']] = len(opts); opts.extend(p['opts'])
h = ['// GENERATED by tools/gen_params.py from data/params.json. Do not edit.', '#pragma once', '#include <cstdint>', 'namespace jpurrr {',
     'enum ParamIndex : int {']
for i, p in enumerate(P): h.append(f'    P_{p["id"]} = {i},')
h += ['    kNumParams = %d' % len(P), '};', '']
h += ['enum class PType : uint8_t { Knob, Slider, Switch, Option, Display };',
      'enum ParamFlags : uint8_t { kNoSave = 1, kMomentary = 2 };',
      'struct ParamDef { const char* id; PType type; const char* label; int min; int max; int def; uint8_t flags; int optStart; int optCount; const char* tip; };',
      'extern const ParamDef kParams[kNumParams];', 'extern const char* const kOptionText[];', 'extern const int kNumOptionText;',
      'int paramIndexById(const char* id);   // -1 when unknown', '}']
open(os.path.join(root, 'core/include/jpurrr/params_gen.h'), 'w').write('\n'.join(h) + '\n')
tm = {'k': 'Knob', 's': 'Slider', 'w': 'Switch', 'o': 'Option', 'd': 'Display'}
c = ['// GENERATED by tools/gen_params.py from data/params.json. Do not edit.', '#include "jpurrr/params_gen.h"', '#include <cstring>', 'namespace jpurrr {', 'const ParamDef kParams[kNumParams] = {']
for p in P:
    fl = (1 if p['nosave'] else 0) | (2 if p['mom'] else 0)
    st = start.get(p['id'], 0); n = len(p['opts']) if p['opts'] else 0
    c.append(f'    {{"{p["id"]}", PType::{tm[p["t"]]}, "{esc(p["label"])}", {p["min"]}, {p["max"]}, {p["def"]}, {fl}, {st}, {n}, "{esc(p["tip"])}"}},')
c += ['};', 'const char* const kOptionText[] = {']
for o in opts: c.append(f'    "{esc(o)}",')
c += ['};', f'const int kNumOptionText = {len(opts)};',
      'int paramIndexById(const char* id) { for (int i = 0; i < kNumParams; ++i) if (!std::strcmp(kParams[i].id, id)) return i; return -1; }', '}']
open(os.path.join(root, 'core/src/params_gen.cpp'), 'w').write('\n'.join(c) + '\n')
print(len(P), 'params,', len(opts), 'option strings')
